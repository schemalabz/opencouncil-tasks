#!/usr/bin/env node
/**
 * Fetch the frozen vectors the fusion differential suites compare against.
 *
 *   node scripts/fetch-fusion-fixtures.mjs            # the conformance tier
 *   node scripts/fetch-fusion-fixtures.mjs --all      # every artifact
 *
 * Written in Node rather than shell on purpose: `python3` was removed from both
 * images when the engine was ported, and `sha256sum` is not `shasum`, so a
 * shell version would work on one machine and not the other.
 *
 * The artifacts were frozen from `fusion/*.py` at the
 * `python-engine-last-known-good` tag before it was deleted. They hold verbatim
 * speech from public council sessions, which is why they are hosted separately
 * and not in git. What *is* in git is the sha256 of each one, and this script
 * refuses to leave behind a file that does not match it: an artifact
 * regenerated by anything other than the archived CPython 3.14.6 produces
 * different numbers, and a suite comparing against those would pass while
 * measuring nothing.
 */
import { createHash } from "crypto";
import { gunzipSync } from "zlib";
import fs from "fs";
import os from "os";
import path from "path";

const RELEASE = "https://github.com/angelospk/s47-window-vectors/releases/download/v1";

/**
 * Every artifact, with the committed index that pins it.
 *
 * `tier` is what a run actually costs. The conformance suite reproduces the
 * four integers per arm that `fusion/CONTRACT.md` publishes, and those are a
 * function of the inputs alone — it reads no oracle, so it needs half a
 * megabyte. The oracles buy a field-by-field comparison of every window, which
 * is the evidence for the port being faithful rather than merely correct, and
 * costs twenty times as much to carry around.
 */
const ARTIFACTS = [
    { file: "fixture_inputs_391.json", index: "FIXTURE_INPUTS.json", tier: "conformance" },
    { file: "oracle_rules_off_391.json", index: "ORACLE_rules_off.json", tier: "all" },
    { file: "oracle_rules_off_production_391.json", index: "ORACLE_rules_off_production.json", tier: "all" },
    { file: "oracle_rules_on_production_391.json", index: "ORACLE_rules_on_production.json", tier: "all" },
    { file: "msa_vectors_391.json", index: "MSA_VECTORS_391.json", tier: "all" },
    { file: "normalize_vectors.json", index: "NORMALIZE_VECTORS.json", tier: "all" },
];

const repoRoot = path.resolve(import.meta.dirname, "..");
const indexDir = path.join(repoRoot, "tests/fusion");
const bundle =
    process.env.FUSION_FIXTURES_DIR ?? path.join(os.homedir(), ".cache/oc-public/chooser-2026-08-25");

const wantAll = process.argv.includes("--all");
const wanted = ARTIFACTS.filter((a) => wantAll || a.tier === "conformance");

function sha256(buf) {
    return createHash("sha256").update(buf).digest("hex");
}

/** Already there and already correct? Then downloading it again proves nothing. */
function satisfied(artifact, expected) {
    const target = path.join(bundle, artifact.file);
    if (!fs.existsSync(target)) return false;
    return sha256(fs.readFileSync(target)) === expected;
}

async function fetchOne(artifact) {
    const { sha256: expected, file: named } = JSON.parse(
        fs.readFileSync(path.join(indexDir, artifact.index), "utf8"),
    );
    if (named !== artifact.file) {
        throw new Error(`${artifact.index} pins ${named}, not ${artifact.file}`);
    }

    if (satisfied(artifact, expected)) {
        console.log(`  ok       ${artifact.file} (already present, sha256 matches)`);
        return;
    }

    const url = `${RELEASE}/${artifact.file}.gz`;
    const response = await fetch(url, { redirect: "follow" });
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);

    const plain = gunzipSync(Buffer.from(await response.arrayBuffer()));
    const got = sha256(plain);
    if (got !== expected) {
        // Deliberately not written to disk. A mismatched artifact on disk is
        // worse than none: the suite would compare against it and pass.
        throw new Error(
            `${artifact.file} sha256 ${got}, expected ${expected} from ${artifact.index}. ` +
                `Not written. This is not the artifact this repo was pinned against.`,
        );
    }

    fs.mkdirSync(bundle, { recursive: true });
    const target = path.join(bundle, artifact.file);
    // Write beside and rename, so an interrupted run cannot leave a truncated
    // artifact that the next one would then verify and reject for ever.
    const staging = `${target}.partial`;
    fs.writeFileSync(staging, plain);
    fs.renameSync(staging, target);
    console.log(`  fetched  ${artifact.file} (${(plain.length / 1e6).toFixed(1)} MB, sha256 verified)`);
}

console.log(`into ${bundle}`);
console.log(wantAll ? "tier: all artifacts" : "tier: conformance only (pass --all for the rest)");
let failed = 0;
for (const artifact of wanted) {
    try {
        await fetchOne(artifact);
    } catch (error) {
        failed++;
        console.error(`  FAILED   ${artifact.file}: ${error.message}`);
    }
}
if (failed) {
    console.error(`\n${failed} of ${wanted.length} could not be verified.`);
    process.exit(1);
}
console.log(`\n${wanted.length} artifact(s) present and verified.`);
