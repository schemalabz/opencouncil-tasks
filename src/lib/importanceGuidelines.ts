/**
 * How a subject's importance for notifications is judged. One text, read at two moments:
 *
 * - `agenda`: before the meeting, by the agenda task, from the agenda alone. It sees every item,
 *   so it can hold "high" to one or two for a meeting.
 * - `debate`: after the meeting, by the step that writes a subject's description, from the whole
 *   debate of that subject. Only here can a disagreement or the presence of residents count, and
 *   one call sees one subject, so there is no limit for a meeting.
 *
 * At both moments "normal" needs a reason and is not the default, and the two values are judged
 * apart: a subject that matters only around its place is "doNotNotify" with a radius.
 */
export function importanceGuidelines(when: 'agenda' | 'debate'): string {
    const debate = when === 'debate';
    return `ΣΗΜΑΣΙΑ ΓΙΑ ΤΙΣ ΕΙΔΟΠΟΙΗΣΕΙΣ:
${debate
        ? 'Μετά τη συνεδρίαση στέλνεται ειδοποίηση στους δημότες. Κρίνε από ΟΛΗ τη συζήτηση του θέματος.'
        : 'Πριν από τη συνεδρίαση στέλνεται ειδοποίηση στους δημότες για τα θέματα της ημερήσιας διάταξης.'}
Οι δύο τιμές κρίνονται χωριστά. Το topicImportance αφορά δημότες σε όλη την πόλη, όπου κι αν μένουν. Το proximityImportance αφορά όσους μένουν κοντά στην τοποθεσία του θέματος.
Ένα θέμα μπορεί να μην ενδιαφέρει την πόλη και να ενδιαφέρει τη γειτονιά του.

**topicImportance - ΠΡΟΣΟΧΗ: Μη χρησιμοποιείς "high" εύκολα!**

"doNotNotify" - ΔΕΝ στέλνεται ειδοποίηση:
✓ Έγκριση πρακτικών προηγούμενης συνεδρίασης
✓ Διορισμοί επιτροπών
✓ Τυπικές διαδικαστικές εγκρίσεις
✓ Ανακοινώσεις χωρίς απόφαση${debate ? `
✓ Θέμα που πέρασε χωρίς ουσιαστική συζήτηση και δεν αλλάζει κάτι για τους δημότες` : ''}
✓ Θέμα που ενδιαφέρει μόνο όσους μένουν κοντά στην τοποθεσία του ΚΑΙ δεν ισχύει ${debate ? 'κανένα από τα κριτήρια' : 'το κριτήριο'} του "normal": εδώ "doNotNotify", και παρακάτω "near" αν αφορά ένα σημείο (μία ράμπα, μία άδεια, ένας δρόμος) ή "wide" αν αφορά ευρύτερη περιοχή

"normal" - Κανονική ειδοποίηση, ${debate ? 'όταν ισχύει τουλάχιστον ένα' : 'όταν ισχύει το εξής'} (ακόμα κι αν το θέμα έχει τοποθεσία):
✓ Αλλάζει κάτι για δημότες σε όλη την πόλη ή σε μεγάλο μέρος της: μια υπηρεσία, ένα τέλος, έναν κανόνα${debate ? `
✓ Υπήρξε πραγματική διαφωνία
✓ Μίλησαν κάτοικοι ή φορείς` : ''}

"high" - Υψηλή σημασία (ΣΠΑΝΙΟ${debate ? '' : ' - μόνο 1-2 ανά συνεδρίαση'}):
✓ Δημοτικός προϋπολογισμός
✓ Φορολογία (αύξηση/μείωση)
✓ Μεγάλες υποδομές (μετρό, αυτοκινητόδρομοι)
✓ Κρίσιμες υπηρεσίες (σχολεία, νοσοκομεία, ασφάλεια)
✓ City-wide ordinances που επηρεάζουν όλους

Κριτήρια για "high":
1. Επηρεάζει ΟΛΟΥΣ τους δημότες ΚΑΙ
${debate ? `2. Η συζήτηση ήταν πολύ ουσιαστική (όχι απλή έγκριση) ΚΑΙ
3.` : '2.'} Έχει σημαντικό αντίκτυπο (οικονομικό, κοινωνικό, ασφάλεια)

**proximityImportance - Γεωγραφική ακτίνα:**

"none" - Δεν έχει τοποθεσία:
✓ Προϋπολογισμός
✓ City-wide πολιτικές
✓ Διοικητικά θέματα
✓ Οτιδήποτε χωρίς τοποθεσία

"near" - Η άμεση γειτονιά (ΠΡΟΕΠΙΛΟΓΗ αν υπάρχει τοποθεσία):
✓ Μεμονωμένη άδεια οικοδομής
✓ Μία επιχείρηση
✓ Επισκευή συγκεκριμένου δρόμου
✓ Τοπικό πάρκο

"wide" - Η ευρύτερη περιοχή:
✓ Πολυώροφο κτίριο (>6 ορόφους)
✓ Αυτοκινητόδρομος/μεγάλος δρόμος
✓ Χώρος εκδηλώσεων με όχληση (γήπεδο, συναυλιακός χώρος)
✓ Εργοστάσιο/βιομηχανική εγκατάσταση
✓ Δίκτυο (π.χ. "ποδηλατόδρομοι σε 5 συνοικίες")
✓ Χώρος που χρησιμοποιεί ολόκληρη περιοχή (μεγάλο πάρκο, κεντρική πλατεία)

importanceReason: μία σύντομη πρόταση που λέει γιατί έδωσες αυτές τις τιμές.`;
}
